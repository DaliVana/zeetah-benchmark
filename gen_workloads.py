#!/usr/bin/env python3
"""Generate per-engine workload source for the compiled-language harnesses.

Reads `benchmarks.json` (via `bench_common`) and emits, into `gen/`, one source
file per compiled engine with that engine's resolved workload table (patterns
already in the engine's required form), the regex-redux member list, the size
list and a couple of scalars. The harnesses keep all timing / model logic; the
generated files are pure DATA, so a pattern is declared in exactly one place
(`benchmarks.json`) and can never drift across harnesses.

Pattern strings are emitted with `bench_common.escape_literal`, which doubles
every backslash — making the literal valid in Zig, Rust, C++ and C# normal
(non-raw) string literals simultaneously (see bench_common for why).

The Python harnesses do NOT use generated files; they import `bench_common`
directly. Run from any cwd: output always lands in `<repo>/gen/`.
"""
import os

import bench_common as bc

HERE = os.path.dirname(os.path.abspath(__file__))
GEN = os.path.join(HERE, "gen")

AUTO = "// AUTO-GENERATED by gen_workloads.py from benchmarks.json — DO NOT EDIT."
AUTO_HASH = "# AUTO-GENERATED by gen_workloads.py from benchmarks.json — DO NOT EDIT."


def lit(s: str) -> str:
    return '"' + bc.escape_literal(s) + '"'


def b(x: bool) -> str:
    return "true" if x else "false"


# --- Zig (zeetah runtime, zeetah-dfa, mvzr) ---------------------------------

def gen_zig(engine: str, path: str) -> None:
    wls = bc.workloads_for(engine)
    sizes = bc.sizes_for(engine)
    redux = bc.redux_for(engine)
    lines = [AUTO, "", "pub const Kind = enum { corpus, pathological };", ""]
    lines.append("pub const Workload = struct {")
    lines.append("    id: []const u8,")
    lines.append("    pattern: []const u8,")
    lines.append("    kind: Kind,")
    lines.append("    multiline: bool,")
    lines.append("    spans: bool,")
    lines.append("    grep: bool,")
    lines.append("    captures: bool,")
    lines.append("    force_reject: bool,")
    lines.append("};")
    lines.append("")
    lines.append("pub const workloads = [_]Workload{")
    for w in wls:
        lines.append(
            f"    .{{ .id = {lit(w.id)}, .pattern = {lit(w.pattern)}, "
            f".kind = .{w.kind}, .multiline = {b(w.multiline)}, "
            f".spans = {b(w.spans)}, .grep = {b(w.grep)}, "
            f".captures = {b(w.captures)}, .force_reject = {b(w.force_reject)} }},"
        )
    lines.append("};")
    lines.append("")
    members = ", ".join(lit(m) for m in redux)
    lines.append(f"pub const redux_members = [_][]const u8{{ {members} }};")
    szs = ", ".join(str(s) for s in sizes)
    lines.append(f"pub const corpus_sizes = [_]usize{{ {szs} }};")
    lines.append(f"pub const synthetic_len: usize = {bc.synthetic_len()};")
    lines.append(f"pub const redux_size: usize = {bc.redux_size()};")
    lines.append("")
    _write(path, "\n".join(lines))


# --- Rust (shared by rust-regex and fancy-regex — identical tables) ---------

def gen_rust(engine: str, path: str) -> None:
    wls = bc.workloads_for(engine)
    sizes = bc.sizes_for(engine)
    redux = bc.redux_for(engine)
    lines = [AUTO, "", "#[derive(PartialEq, Clone, Copy)]",
             "pub enum Kind { Corpus, Pathological }", "",
             "pub struct Workload {",
             "    pub id: &'static str,",
             "    pub pattern: &'static str,",
             "    pub kind: Kind,",
             "    pub spans: bool,",
             "    pub grep: bool,",
             "    pub captures: bool,",
             "    pub force_reject: bool,",
             "}", "",
             "pub static WORKLOADS: &[Workload] = &["]
    for w in wls:
        k = "Kind::Pathological" if w.kind == "pathological" else "Kind::Corpus"
        lines.append(
            f"    Workload {{ id: {lit(w.id)}, pattern: {lit(w.pattern)}, "
            f"kind: {k}, spans: {b(w.spans)}, grep: {b(w.grep)}, "
            f"captures: {b(w.captures)}, force_reject: {b(w.force_reject)} }},"
        )
    lines.append("];")
    lines.append("")
    members = ", ".join(lit(m) for m in redux)
    lines.append(f"pub static REDUX_MEMBERS: &[&str] = &[{members}];")
    szs = ", ".join(str(s) for s in sizes)
    lines.append(f"pub static CORPUS_SIZES: &[usize] = &[{szs}];")
    lines.append(f"pub const SYNTHETIC_LEN: usize = {bc.synthetic_len()};")
    lines.append(f"pub const REDUX_SIZE: usize = {bc.redux_size()};")
    lines.append("")
    _write(path, "\n".join(lines))


# --- C++ (RE2) --------------------------------------------------------------

def gen_cpp(engine: str, path: str) -> None:
    wls = bc.workloads_for(engine)
    sizes = bc.sizes_for(engine)
    redux = bc.redux_for(engine)
    lines = [AUTO, "", "#pragma once", "#include <cstddef>", "",
             "struct Workload {",
             "    const char* id;",
             "    const char* pattern;",
             "    bool pathological;",
             "    bool spans;",
             "    bool grep;",
             "    bool captures;",
             "    bool force_reject;",
             "};", "",
             "static const Workload WORKLOADS[] = {"]
    for w in wls:
        lines.append(
            f"    {{ {lit(w.id)}, {lit(w.pattern)}, "
            f"{b(w.kind == 'pathological')}, {b(w.spans)}, {b(w.grep)}, "
            f"{b(w.captures)}, {b(w.force_reject)} }},"
        )
    lines.append("};")
    lines.append(f"static const size_t WORKLOADS_N = {len(wls)};")
    lines.append("")
    members = ", ".join(lit(m) for m in redux)
    lines.append(f"static const char* REDUX_MEMBERS[] = {{{members}}};")
    lines.append(f"static const size_t REDUX_MEMBERS_N = {len(redux)};")
    szs = ", ".join(str(s) for s in sizes)
    lines.append(f"static const size_t CORPUS_SIZES[] = {{{szs}}};")
    lines.append(f"static const size_t CORPUS_SIZES_N = {len(sizes)};")
    lines.append(f"static const size_t SYNTHETIC_LEN = {bc.synthetic_len()};")
    lines.append(f"static const size_t REDUX_SIZE = {bc.redux_size()};")
    lines.append("")
    _write(path, "\n".join(lines))


# --- C# (.NET) --------------------------------------------------------------

def gen_csharp(engine: str, path: str) -> None:
    wls = bc.workloads_for(engine)
    sizes = bc.sizes_for(engine)
    redux = bc.redux_for(engine)
    lines = [AUTO, "", "internal static class Workloads", "{",
             "    internal struct W",
             "    {",
             "        public string Id;",
             "        public string Pattern;",
             "        public bool Pathological;",
             "        public bool Spans;",
             "        public bool Grep;",
             "        public bool Captures;",
             "        public bool ForceReject;",
             "    }", "",
             "    internal static readonly W[] All = {"]
    for w in wls:
        lines.append(
            f"        new W {{ Id = {lit(w.id)}, Pattern = {lit(w.pattern)}, "
            f"Pathological = {b(w.kind == 'pathological')}, Spans = {b(w.spans)}, "
            f"Grep = {b(w.grep)}, Captures = {b(w.captures)}, "
            f"ForceReject = {b(w.force_reject)} }},"
        )
    lines.append("    };")
    lines.append("")
    members = ", ".join(lit(m) for m in redux)
    lines.append(f"    internal static readonly string[] ReduxMembers = {{ {members} }};")
    szs = ", ".join(str(s) for s in sizes)
    lines.append(f"    internal static readonly int[] CorpusSizes = {{ {szs} }};")
    lines.append(f"    internal const int SyntheticLen = {bc.synthetic_len()};")
    lines.append(f"    internal const int ReduxSize = {bc.redux_size()};")
    lines.append("}")
    lines.append("")
    _write(path, "\n".join(lines))


def _write(path: str, text: str) -> None:
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def main() -> None:
    os.makedirs(GEN, exist_ok=True)
    gen_zig("zeetah", os.path.join(GEN, "workloads_zeetah.zig"))
    gen_zig("zeetah-dfa", os.path.join(GEN, "workloads_zeetah_dfa.zig"))
    gen_zig("mvzr", os.path.join(GEN, "workloads_mvzr.zig"))
    # rust-regex and fancy-regex resolve to identical tables; emit once.
    gen_rust("rust-regex", os.path.join(GEN, "workloads_rust.rs"))
    gen_cpp("re2", os.path.join(GEN, "workloads_re2.hpp"))
    gen_csharp("dotnet-regex", os.path.join(GEN, "workloads_dotnet.cs"))
    print(f"generated workload sources in {GEN}")


if __name__ == "__main__":
    main()
