#!/usr/bin/env python3
"""Merge per-engine CSVs into a comparison report.

Reads results.csv (the concatenated rows from all harnesses, with a header)
and writes results.md. Enforces a correctness gate: for every
(workload, input_bytes) the match_count must agree across all engines that
produced a real result. The `pathological` workload is exempt because
zeetah's ReDoS guard deliberately *rejects* the pattern while RE2 and Rust
run it — that divergence is itself a reported finding, not a bug.

The real GPT-4 `tokenizer` workload is NOT exempt: it is the motivating
pattern, so the gate must hold there. Engines that genuinely cannot express
it (base `regex`, RE2, mvzr — no look-around; Python stdlib `re` — no
`\p{}`) emit REJECTED and are skipped. The engines that do run it —
zeetah, `fancy-regex` (tiktoken/rustbpe's engine), .NET (possessive
written as the equivalent atomic group) and the PyPI `regex` module — must
agree, which is exactly the correctness signal we want gated.

Exit code 1 if the correctness gate fails.
"""
import csv
import sys
from collections import defaultdict

RESULTS = sys.argv[1] if len(sys.argv) > 1 else "results.csv"
OUT = sys.argv[2] if len(sys.argv) > 2 else "results.md"

ENGINE_ORDER = ["zeetah", "zeetah-dfa", "mvzr", "re2", "rust-regex", "fancy-regex", "dotnet-regex", "python-re", "python-regex"]


def fmt_ns(ns):
    ns = int(ns)
    if ns < 0:
        return "—"
    if ns >= 1_000_000:
        return f"{ns/1_000_000:.2f} ms"
    if ns >= 1_000:
        return f"{ns/1_000:.2f} µs"
    return f"{ns} ns"


def human_bytes(n):
    n = int(n)
    if n >= 1_048_576:
        return f"{n//1_048_576} MiB"
    if n >= 1024:
        return f"{n//1024} KiB"
    return f"{n} B"


def main():
    rows = []
    with open(RESULTS, newline="") as f:
        for r in csv.DictReader(f):
            rows.append(r)

    # group: (workload, input_bytes) -> engine -> row
    groups = defaultdict(dict)
    workloads_seen = []
    for r in rows:
        key = (r["workload"], int(r["input_bytes"]))
        groups[key][r["engine"]] = r
        if r["workload"] not in workloads_seen:
            workloads_seen.append(r["workload"])

    # --- correctness gate ---
    gate_failures = []
    for (wl, ib), per_engine in groups.items():
        # `pathological` only: engines legitimately diverge there (zeetah's
        # ReDoS guard rejects it while RE2/Rust run it). Every other workload —
        # including the real GPT-4 `tokenizer` — must agree across the engines
        # that produced an `ok` result (zeetah vs fancy-regex for tokenizer).
        if wl == "pathological":
            continue
        counts = {
            e: int(row["match_count"])
            for e, row in per_engine.items()
            if row["note"] == "ok"
        }
        uniq = set(counts.values())
        if len(uniq) > 1:
            gate_failures.append((wl, ib, counts))

    md = []
    md.append("# Cross-Engine Regex Benchmark Results\n")
    md.append(
        "Generated by `run_all.sh`. Each harness times "
        "the same operation (count all leftmost, non-overlapping matches) over "
        "byte-identical input from a deterministic corpus. `compile` and "
        "`search` are timed in separate loops; reported figures are the "
        "**median** of the timed iterations (each loop sized to run ≥50 ms, "
        "bounded to [5, 500] iterations).\n"
    )

    if gate_failures:
        md.append("## ⚠️ Correctness gate FAILED\n")
        md.append(
            "Match counts disagree across engines for the rows below — the "
            "timing comparison for those rows is **not valid** until the "
            "semantic difference is explained:\n"
        )
        for wl, ib, counts in gate_failures:
            md.append(f"- `{wl}` @ {human_bytes(ib)}: {counts}")
        md.append("")

    for wl in workloads_seen:
        md.append(f"## Workload: `{wl}`\n")
        keys = sorted(k for k in groups if k[0] == wl)
        md.append(
            "| Input | Engine | Compile | Search (median) | Throughput | Matches | Rel. speed | Note |"
        )
        md.append(
            "|-------|--------|---------|-----------------|------------|---------|-----------|------|"
        )
        for key in keys:
            per_engine = groups[key]
            # fastest search among ok engines for this row
            ok_times = [
                int(per_engine[e]["search_ns_per_op"])
                for e in per_engine
                if per_engine[e]["note"] == "ok"
            ]
            best = min(ok_times) if ok_times else None
            for e in ENGINE_ORDER:
                if e not in per_engine:
                    continue
                row = per_engine[e]
                note = row["note"]
                if note == "ok":
                    s_ns = int(row["search_ns_per_op"])
                    rel = f"{s_ns/best:.2f}×" if best else "—"
                    search = fmt_ns(s_ns)
                    tput = f"{float(row['throughput_mb_s']):.1f} MB/s"
                    matches = row["match_count"]
                else:
                    search = "—"
                    rel = "—"
                    tput = "—"
                    matches = "—"
                md.append(
                    f"| {human_bytes(key[1])} | {e} | {fmt_ns(row['compile_ns'])} "
                    f"| {search} | {tput} | {matches} | {rel} | {note} |"
                )
        md.append("")

    with open(OUT, "w") as f:
        f.write("\n".join(md) + "\n")

    print(f"wrote {OUT}")
    if gate_failures:
        print("CORRECTNESS GATE FAILED:", file=sys.stderr)
        for wl, ib, counts in gate_failures:
            print(f"  {wl} @ {ib}B: {counts}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
